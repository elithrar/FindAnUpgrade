"""Emit exact-ID primary classifications, never title-group or secondary labels."""
from pathlib import Path
import argparse, hashlib, json

ROOT = Path(__file__).resolve().parents[1]
STATUSES = {"New": "verifiedNew", "Updated": "verifiedUpdated", "Unchanged": "verifiedUnchanged"}

def render(source):
    assert source["version"] == "1"
    assert (source["zoneCount"], source["titleGroupCount"], source["questIdCount"]) == (18, 998, 1194)
    rows = source["quests"]
    assert len(rows) == 1194 and len({r["id"] for r in rows}) == 1194
    assert all(type(r["id"]) is int and r["id"] > 0 and r["status"] in STATUSES for r in rows)
    assert sum(r["status"] == "New" for r in rows) == 218
    lines = ["-- Generated by tools/generate_data.py from per-ID primary evidence.", "-- Do not edit or expand title groups into new IDs.", "local _, N = ...", "N.Data = { collectedAt = \"2026-10-14\", newCount = 218, statusById = {"]
    for row in sorted(rows, key=lambda r: r["id"]):
        lines.append(f'    [{row["id"]}] = "{STATUSES[row["status"]]}",')
    lines.extend(["} }", ""])
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(); parser.add_argument("--check", action="store_true"); args = parser.parse_args()
    raw = (ROOT / "data/primary-statuses.json").read_bytes()
    output = render(json.loads(raw)).encode()
    path = ROOT / "QuestBrief/Data/Quests.lua"
    if args.check:
        assert path.read_bytes() == output, "Generated classification table is stale"
    else:
        path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(output)
    print(f"1194 exact IDs; 218 verifiedNew; primary evidence SHA256 {hashlib.sha256(raw).hexdigest()}")

if __name__ == "__main__": main()
